#!/usr/bin/env python3
"""
site_tools.py - maintenance tool for the Aivora AI static site (GitHub Pages).

  python tools/site_tools.py generate   -> rebuild sitemap.xml, sitemap.html, llms.txt
  python tools/site_tools.py check      -> audit all pages, write site_check_report.md
  python tools/site_tools.py all        -> generate, then check

Standard library only. `check` exits with code 1 if any ERROR is found
(warnings never fail the build).
"""
import html
import json
import os
import re
import subprocess
import sys
from datetime import date
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlparse, unquote

BASE_URL = os.environ.get("SITE_URL", "https://aivoraai.github.io").rstrip("/")
SITE_NAME = os.environ.get("SITE_NAME", "Aivora AI")
ROOT = Path(os.environ.get("SITE_ROOT", ".")).resolve()

# Files/folders that are never listed in sitemaps and never audited as pages
EXCLUDE_DIRS = {".git", ".github", "_seo_backups", "scripts", "tools", "node_modules", "assets", "images", "lhci"}
EXCLUDE_FILES = {"404.html", "thank-you.html", "sitemap.html", "BingSiteAuth.xml"}
EXCLUDE_PREFIXES = ("google", "yandex")

AUTO_XML_NOTE = "Auto-generated by tools/site_tools.py"
LLMS_START, LLMS_END = "<!-- AUTO-START -->", "<!-- AUTO-END -->"
MAP_START, MAP_END = "<!-- AUTO-SITEMAP-START -->", "<!-- AUTO-SITEMAP-END -->"

VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta",
        "param", "source", "track", "wbr"}
OPTIONAL_END = {"p", "li", "dt", "dd", "tr", "td", "th", "thead", "tbody", "tfoot",
                "option", "optgroup", "colgroup"}


# --------------------------------------------------------------------------- #
# HTML parsing
# --------------------------------------------------------------------------- #
class Page(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.doctype = False
        self.html_lang = None
        self.title = ""
        self._in_title = False
        self.meta = {}          # name/property -> content
        self.canonical = None
        self.h1 = 0
        self.imgs = []          # attr dicts
        self.links = []         # (tag, attr, value)
        self.ids = []
        self.jsonld = []
        self._in_jsonld = False
        self._jsonld_buf = ""
        self.inline_styles = []
        self.stack = []
        self.tag_errors = []
        self.has_main_h1_text = False
        self.stylesheets = []
        self.inline_css = ""
        self._in_style = False

    def handle_decl(self, decl):
        if decl.lower().startswith("doctype"):
            self.doctype = True

    def handle_starttag(self, tag, attrs):
        a = dict((k.lower(), (v or "")) for k, v in attrs)
        if tag == "html":
            self.html_lang = a.get("lang")
        elif tag == "title":
            self._in_title = True
        elif tag == "meta":
            key = (a.get("name") or a.get("property") or a.get("http-equiv") or "").lower()
            if key:
                self.meta[key] = a.get("content", "")
            if "charset" in a:
                self.meta["charset"] = a["charset"]
        elif tag == "link":
            rel = a.get("rel", "").lower()
            if "canonical" in rel:
                self.canonical = a.get("href")
            if "stylesheet" in rel and a.get("href"):
                self.stylesheets.append(a["href"])
            if a.get("href"):
                self.links.append(("link", "href", a["href"]))
        elif tag == "h1":
            self.h1 += 1
        elif tag == "img":
            self.imgs.append(a)
            if a.get("src"):
                self.links.append(("img", "src", a["src"]))
        elif tag == "a" and a.get("href") is not None:
            self.links.append(("a", "href", a["href"]))
        elif tag in ("script", "source", "iframe", "video", "audio") and a.get("src"):
            self.links.append((tag, "src", a["src"]))
        elif tag == "script" and a.get("type", "").lower() == "application/ld+json":
            self._in_jsonld = True
            self._jsonld_buf = ""
        elif tag == "style":
            self._in_style = True
        if "id" in a and a["id"]:
            self.ids.append(a["id"])
        if "style" in a:
            self.inline_styles.append((tag, a["style"]))
        if tag not in VOID:
            self.stack.append(tag)

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag not in VOID and self.stack and self.stack[-1] == tag:
            self.stack.pop()

    def handle_endtag(self, tag):
        if tag == "title":
            self._in_title = False
        if tag == "style":
            self._in_style = False
        if tag == "script" and self._in_jsonld:
            self._in_jsonld = False
            self.jsonld.append(self._jsonld_buf)
        if tag in VOID:
            return
        if tag in self.stack:
            while self.stack and self.stack[-1] != tag:
                skipped = self.stack.pop()
                if skipped not in OPTIONAL_END:
                    self.tag_errors.append(f"<{skipped}> is not closed before </{tag}>")
            if self.stack:
                self.stack.pop()
        else:
            self.tag_errors.append(f"stray closing tag </{tag}>")

    def handle_data(self, data):
        if self._in_title:
            self.title += data
        if self._in_jsonld:
            self._jsonld_buf += data
        if self._in_style:
            self.inline_css += data

    def close(self):
        super().close()
        for t in self.stack:
            if t not in OPTIONAL_END and t not in ("html", "body", "head"):
                self.tag_errors.append(f"<{t}> is never closed")


def parse(path: Path) -> Page:
    p = Page()
    p.feed(path.read_text(encoding="utf-8", errors="replace"))
    p.close()
    return p


# --------------------------------------------------------------------------- #
# Page discovery
# --------------------------------------------------------------------------- #
def all_pages():
    pages = []
    for path in sorted(ROOT.rglob("*.html")):
        rel = path.relative_to(ROOT)
        if any(part in EXCLUDE_DIRS or part.startswith(".") for part in rel.parts[:-1]):
            continue
        if rel.name in EXCLUDE_FILES or rel.name.startswith(EXCLUDE_PREFIXES):
            continue
        pages.append(rel)
    return pages


def page_url(rel: Path, parsed: Page) -> str:
    """Prefer the page's own canonical URL when it points at this site."""
    if parsed.canonical and parsed.canonical.startswith(BASE_URL):
        return parsed.canonical
    posix = rel.as_posix()
    if posix == "index.html":
        return BASE_URL + "/"
    return f"{BASE_URL}/{posix}"


def is_noindex(p: Page) -> bool:
    return "noindex" in p.meta.get("robots", "").lower()


def last_modified(rel: Path) -> str:
    try:
        out = subprocess.run(
            ["git", "log", "-1", "--format=%cs", "--", str(rel)],
            cwd=ROOT, capture_output=True, text=True, check=True,
        ).stdout.strip()
        if out:
            return out
    except Exception:
        pass
    return date.fromtimestamp((ROOT / rel).stat().st_mtime).isoformat()


def collect():
    items = []
    for rel in all_pages():
        p = parse(ROOT / rel)
        if is_noindex(p):
            continue
        title = re.sub(r"\s+", " ", p.title).strip() or rel.stem.replace("-", " ").title()
        items.append({
            "rel": rel,
            "url": page_url(rel, p),
            "title": title,
            "desc": re.sub(r"\s+", " ", p.meta.get("description", "")).strip(),
            "lastmod": last_modified(rel),
            "is_blog": rel.parts[0] == "blog" and len(rel.parts) > 1,
        })
    return items


def priority(item):
    name = item["rel"].as_posix()
    if name == "index.html":
        return "1.0", "daily"
    if name == "blog.html":
        return "0.9", "daily"
    if item["is_blog"]:
        return "0.7", "monthly"
    if name in ("privacy.html", "terms.html", "disclosure.html"):
        return "0.3", "yearly"
    return "0.6", "monthly"


# --------------------------------------------------------------------------- #
# Generators
# --------------------------------------------------------------------------- #
def write_if_changed(path: Path, text: str):
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old != text:
        path.write_text(text, encoding="utf-8")
        print(f"updated  {path.relative_to(ROOT)}")
    else:
        print(f"unchanged {path.relative_to(ROOT)}")


def gen_sitemap_xml(items):
    esc = html.escape
    rows = []
    for it in sorted(items, key=lambda i: (-float(priority(i)[0]), i["url"])):
        prio, freq = priority(it)
        rows.append(
            "  <url>\n"
            f"    <loc>{esc(it['url'])}</loc>\n"
            f"    <lastmod>{it['lastmod']}</lastmod>\n"
            f"    <changefreq>{freq}</changefreq>\n"
            f"    <priority>{prio}</priority>\n"
            "  </url>"
        )
    xml = ('<?xml version="1.0" encoding="UTF-8"?>\n'
           f"<!-- {AUTO_XML_NOTE} -->\n"
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
           + "\n".join(rows) + "\n</urlset>\n")
    write_if_changed(ROOT / "sitemap.xml", xml)


def gen_sitemap_html(items):
    esc = html.escape
    main = [i for i in items if not i["is_blog"]]
    blog = [i for i in items if i["is_blog"]]

    def block(heading, lst):
        if not lst:
            return ""
        lis = "\n".join(
            f'        <li><a href="{esc(i["url"])}">{esc(i["title"])}</a></li>'
            for i in sorted(lst, key=lambda i: i["title"].lower()))
        return f"      <h2>{heading}</h2>\n      <ul>\n{lis}\n      </ul>\n"

    body = block("Main pages", main) + block("Blog articles", blog)
    section = f"{MAP_START}\n{body}      {MAP_END}"
    path = ROOT / "sitemap.html"

    if path.exists() and MAP_START in path.read_text(encoding="utf-8"):
        text = path.read_text(encoding="utf-8")
        text = re.sub(re.escape(MAP_START) + r".*?" + re.escape(MAP_END), lambda m: section,
                      text, flags=re.S)
    else:
        # First run (or markers missing): write a complete, mobile-ready page.
        text = f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Sitemap | {esc(SITE_NAME)}</title>
  <meta name="description" content="Browse every page and article on {esc(SITE_NAME)}.">
  <link rel="canonical" href="{BASE_URL}/sitemap.html">
  <link rel="stylesheet" href="/style.css">
</head>
<body>
  <main>
    <div class="container" style="max-width:900px;margin:0 auto;padding:1rem;">
      <h1>Sitemap</h1>
      {section}
    </div>
  </main>
</body>
</html>
"""
    write_if_changed(path, text)


def gen_llms_txt(items):
    lines = [LLMS_START, "## Pages", ""]
    for it in sorted([i for i in items if not i["is_blog"]], key=lambda i: i["rel"].as_posix()):
        d = f": {it['desc']}" if it["desc"] else ""
        lines.append(f"- [{it['title']}]({it['url']}){d}")
    blog = [i for i in items if i["is_blog"]]
    if blog:
        lines += ["", "## Blog", ""]
        for it in sorted(blog, key=lambda i: i["lastmod"], reverse=True):
            d = f": {it['desc']}" if it["desc"] else ""
            lines.append(f"- [{it['title']}]({it['url']}){d}")
    lines += ["", LLMS_END]
    section = "\n".join(lines)

    path = ROOT / "llms.txt"
    if path.exists():
        text = path.read_text(encoding="utf-8")
        if LLMS_START in text:
            text = re.sub(re.escape(LLMS_START) + r".*?" + re.escape(LLMS_END),
                          lambda m: section, text, flags=re.S)
        else:
            text = text.rstrip() + "\n\n" + section + "\n"   # keep the existing intro
    else:
        text = f"# {SITE_NAME}\n\n> Official website of {SITE_NAME}.\n\n{section}\n"
    write_if_changed(path, text)


def generate():
    items = collect()
    print(f"{len(items)} indexable pages found")
    gen_sitemap_xml(items)
    gen_sitemap_html(items)
    gen_llms_txt(items)


# --------------------------------------------------------------------------- #
# Audit
# --------------------------------------------------------------------------- #
SKIP_SCHEMES = ("http:", "https:", "mailto:", "tel:", "javascript:", "data:", "sms:", "whatsapp:", "//")


def resolve_local(rel: Path, ref: str):
    ref = ref.strip()
    if not ref or ref.startswith("#") or ref.lower().startswith(SKIP_SCHEMES):
        return None
    ref = ref.split("#")[0].split("?")[0]
    if not ref:
        return None
    ref = unquote(ref)
    target = (ROOT / ref.lstrip("/")) if ref.startswith("/") else (ROOT / rel.parent / ref)
    try:
        target = target.resolve()
        target.relative_to(ROOT)
    except Exception:
        return target
    return target


def exists_on_pages(target: Path) -> bool:
    if target.is_file():
        return True
    if target.is_dir() and (target / "index.html").exists():
        return True
    # GitHub Pages serves /about for about.html
    return target.with_suffix(".html").is_file() if not target.suffix else False


def check():
    errors, warnings = [], []
    css_path = ROOT / "style.css"
    css = css_path.read_text(encoding="utf-8", errors="replace") if css_path.exists() else ""
    if css_path.exists():
        if "@media" not in css:
            warnings.append(("style.css", "No @media queries found - layout may not adapt to mobile."))
        if not re.search(r"img[^{}]*\{[^}]*max-width\s*:\s*100%", css, re.S):
            warnings.append(("style.css", "No `img { max-width:100% }` rule - images can overflow on phones."))
    else:
        warnings.append(("style.css", "File not found."))

    pages = all_pages()
    seen_titles, seen_desc = {}, {}

    for rel in pages:
        name = rel.as_posix()
        p = parse(ROOT / rel)
        E = lambda m: errors.append((name, m))
        W = lambda m: warnings.append((name, m))

        # --- document basics
        if not p.doctype:
            E("Missing <!DOCTYPE html>.")
        if not p.html_lang:
            W('Missing lang attribute on <html> (e.g. lang="en").')
        if "charset" not in p.meta:
            W("Missing <meta charset>.")
        title = re.sub(r"\s+", " ", p.title).strip()
        if not title:
            E("Missing or empty <title>.")
        else:
            if len(title) > 65:
                W(f"Title is {len(title)} chars (aim for <= 60).")
            seen_titles.setdefault(title, []).append(name)
        desc = p.meta.get("description", "").strip()
        if not desc:
            E("Missing meta description.")
        else:
            if not 70 <= len(desc) <= 170:
                W(f"Meta description is {len(desc)} chars (aim for 70-160).")
            seen_desc.setdefault(desc, []).append(name)
        if not p.canonical:
            W("Missing <link rel=canonical>.")
        if p.h1 == 0:
            E("No <h1> on the page.")
        elif p.h1 > 1:
            W(f"{p.h1} <h1> tags (use exactly one).")

        # --- mobile
        vp = p.meta.get("viewport", "")
        if not vp:
            E("MOBILE: missing <meta name=viewport> - page will render zoomed-out on phones.")
        else:
            if "width=device-width" not in vp.replace(" ", ""):
                E("MOBILE: viewport must contain width=device-width.")
            if re.search(r"user-scalable\s*=\s*(no|0)|maximum-scale\s*=\s*1(\.0)?\b", vp):
                W("MOBILE: viewport blocks pinch-zoom (accessibility problem).")
        if not p.stylesheets and not p.inline_css and not p.inline_styles:
            W("No CSS found for this page.")
        for tag, style in p.inline_styles:
            for m in re.finditer(r"(?<![-\w])(?:min-)?width\s*:\s*(\d+)px", style):
                if int(m.group(1)) > 420:
                    W(f"MOBILE: <{tag}> has fixed inline width {m.group(1)}px (wider than a phone).")
            if re.search(r"font-size\s*:\s*([1-9]|1[01])px", style):
                W(f"MOBILE: <{tag}> font-size under 12px is hard to read on phones.")
        if re.search(r"(?<![-\w])width\s*:\s*(\d{3,4})px", p.inline_css):
            wide = [m for m in re.findall(r"(?<![-\w])width\s*:\s*(\d{3,4})px", p.inline_css) if int(m) > 420]
            if wide and "@media" not in p.inline_css:
                W(f"MOBILE: page <style> uses fixed widths ({', '.join(wide[:3])}px) with no @media rules.")

        # --- images
        for img in p.imgs:
            src = img.get("src", "")
            if "alt" not in img:
                E(f"Image without alt attribute: {src or '(no src)'}")
            if not src:
                E("Image with empty src.")
            if "width" not in img and "height" not in img:
                W(f"Image missing width/height (causes layout shift): {src}")
            if img.get("loading") != "lazy" and "logo" not in src.lower():
                W(f"Image not lazy-loaded: {src}")

        # --- broken local links / assets
        for tag, attr, val in p.links:
            if tag == "a" and val.strip() in ("", "#"):
                W('Empty link (href="" or "#").')
                continue
            target = resolve_local(rel, val)
            if target is None:
                continue
            if not exists_on_pages(target):
                E(f"Broken {tag} {attr}: {val}")
        for href in p.stylesheets:
            pass  # already covered by p.links

        # --- structure
        dup = {i for i in p.ids if p.ids.count(i) > 1}
        for d in sorted(dup):
            E(f'Duplicate id="{d}".')
        for m in p.tag_errors[:8]:
            E(f"HTML structure: {m}")
        if len(p.tag_errors) > 8:
            E(f"HTML structure: {len(p.tag_errors) - 8} more tag problems.")

        # --- structured data
        for blob in p.jsonld:
            try:
                json.loads(blob)
            except Exception as ex:
                E(f"Invalid JSON-LD structured data: {ex}")

        # --- in-page anchors
        for tag, attr, val in p.links:
            if tag == "a" and val.startswith("#") and len(val) > 1 and val[1:] not in p.ids:
                W(f"Anchor {val} points to an id that does not exist on this page.")

    for t, names in seen_titles.items():
        if len(names) > 1:
            warnings.append((", ".join(names[:4]), f'Duplicate <title>: "{t}"'))
    for d, names in seen_desc.items():
        if len(names) > 1:
            warnings.append((", ".join(names[:4]), "Duplicate meta description."))

    # --- generated files sanity
    for fname in ("sitemap.xml", "llms.txt", "robots.txt", "manifest.json", "rss.xml"):
        fp = ROOT / fname
        if not fp.exists():
            warnings.append((fname, "File missing."))
            continue
        try:
            if fname.endswith(".xml"):
                import xml.dom.minidom
                xml.dom.minidom.parse(str(fp))
            elif fname.endswith(".json"):
                json.loads(fp.read_text(encoding="utf-8"))
        except Exception as ex:
            errors.append((fname, f"Invalid file: {ex}"))
    robots = ROOT / "robots.txt"
    if robots.exists() and "sitemap:" not in robots.read_text(encoding="utf-8", errors="replace").lower():
        warnings.append(("robots.txt", f"No Sitemap: line (add `Sitemap: {BASE_URL}/sitemap.xml`)."))

    # --- sitemap vs real pages
    sm = ROOT / "sitemap.xml"
    if sm.exists():
        listed = set(re.findall(r"<loc>([^<]+)</loc>", sm.read_text(encoding="utf-8")))
        for u in listed:
            if u.startswith(BASE_URL):
                local = u[len(BASE_URL):].lstrip("/") or "index.html"
                if not exists_on_pages(ROOT / local):
                    errors.append(("sitemap.xml", f"Lists a page that does not exist: {u}"))

    write_report(errors, warnings, len(pages))
    return errors


def write_report(errors, warnings, n_pages):
    def section(title, rows):
        if not rows:
            return f"## {title}\n\nNone \u2705\n\n"
        out = f"## {title} ({len(rows)})\n\n"
        cur = None
        for f, m in sorted(rows):
            if f != cur:
                out += f"\n**{f}**\n\n"
                cur = f
            out += f"- {m}\n"
        return out + "\n"

    text = (f"# Site check report\n\nChecked **{n_pages}** pages on {date.today().isoformat()}.\n\n"
            f"- Errors: **{len(errors)}**\n- Warnings: **{len(warnings)}**\n\n"
            + section("Errors (must fix)", errors) + section("Warnings (should fix)", warnings))
    (ROOT / "site_check_report.md").write_text(text, encoding="utf-8")
    print(text)

    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a", encoding="utf-8") as fh:
            fh.write(text)
    for f, m in errors:
        print(f"::error file={f}::{m}")
    for f, m in warnings[:50]:
        print(f"::warning file={f}::{m}")


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "all"
    if cmd in ("generate", "all"):
        generate()
    if cmd in ("check", "all"):
        errs = check()
        sys.exit(1 if errs else 0)


if __name__ == "__main__":
    main()
